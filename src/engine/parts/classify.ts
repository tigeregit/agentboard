const MCP_RE = /^(mcp__|mcp_|mcp-|user-|plugin-|cursor-|@)/i;

export function toolCategory(name: string, args?: unknown): ToolCategory {
  const n = name.trim();
  for (const [re, cat] of CATEGORY_RULES) if (re.test(n)) return cat;
  // MCP tools are usually prefixed; keep them distinguishable.
  if (MCP_RE.test(n)) return "mcp";
  // Heuristics on args when the name is opaque.
  if (isRec(args)) {
    if (typeof args.command === "string" || typeof args.cmd === "string") return "shell";
    if (typeof args.url === "string") return "web";
    if (typeof args.pattern === "string" || typeof args.query === "string") return "search";
    if (typeof args.old_string === "string" || typeof args.new_string === "string" || typeof args.content === "string") return "edit";
    if (typeof args.path === "string" || typeof args.file_path === "string") return "read";
  }
  return "other";
}

// ---------- argument extraction ----------

function isRec(v: unknown): v is Rec {
  return typeof v === "object" && v !== null && !Array.isArray(v);
}

/** Parse arguments that arrive as a JSON string; return the original otherwise. */
export function parseArgs(input: unknown): unknown {
  if (typeof input !== "string") return input;
  const t = input.trim();
  if (!t.startsWith("{") && !t.startsWith("[")) return input;
  try {
    return JSON.parse(t);
  } catch {
    return input;
  }
}

const FILE_KEYS = ["path", "file_path", "filePath", "file", "target_file", "targetFile", "notebook_path", "relative_workspace_path", "target_notebook", "absolute_path", "filename", "file_name", "dir", "directory", "target_directory", "old_path", "new_path", "source", "destination"];
const FILE_LIST_KEYS = ["paths", "files", "file_paths", "filePaths"];
const COMMAND_KEYS = ["command", "cmd", "commandLine", "command_line", "script", "code"];

export function extractCommand(args: unknown): string | undefined {
  const a = parseArgs(args);
  if (typeof a === "string") return a.trim() || undefined;
  if (!isRec(a)) return undefined;
  for (const k of COMMAND_KEYS) {
    const v = a[k];
    if (typeof v === "string" && v.trim()) return v.trim();
    if (Array.isArray(v) && v.every((x) => typeof x === "string")) return (v as string[]).join(" ");
  }
  // codex local_shell_call: { action: { command: [...] } }
  if (isRec(a.action)) return extractCommand(a.action);
  return undefined;
}

const PATCH_FILE_RE = /^\*\*\* (?:Add|Update|Delete|Move to) File: (.+)$|^(?:---|\+\+\+) [ab]\/(.+)$|^diff --git a\/(\S+)/gm;

export function extractFiles(args: unknown, resultText?: string): string[] {
  const a = parseArgs(args);
  const out = new Set<string>();
  const add = (v: unknown) => {
    if (typeof v === "string" && v.trim() && v.length < 512 && !/\s{2,}/.test(v)) out.add(v.trim());
  };
  if (isRec(a)) {
    for (const k of FILE_KEYS) add(a[k]);
    for (const k of FILE_LIST_KEYS) if (Array.isArray(a[k])) for (const v of a[k] as unknown[]) add(v);
    // apply_patch style input
    const patch = typeof a.input === "string" ? a.input : typeof a.patch === "string" ? a.patch : undefined;
    if (patch) for (const m of patch.matchAll(PATCH_FILE_RE)) add(m[1] ?? m[2] ?? m[3]);
  } else if (typeof a === "string") {
    for (const m of a.matchAll(PATCH_FILE_RE)) add(m[1] ?? m[2] ?? m[3]);
  }
  if (resultText) for (const m of resultText.slice(0, 20_000).matchAll(/^\*\*\* (?:Add|Update|Delete) File: (.+)$/gm)) add(m[1]);
  return Array.from(out);
}

/** Compact one-line rendering of arguments for tables and snippets. */
export function renderArgs(name: string, args: unknown, max = 200): string {
  const cmd = extractCommand(args);
  if (cmd) return oneLine(cmd, max);
  const a = parseArgs(args);
  if (a === undefined || a === null) return "";
  if (typeof a === "string") return oneLine(a, max);
  if (isRec(a)) {
    const files = extractFiles(a);
    const parts: string[] = [];
    if (files.length) parts.push(files.join(", "));
    for (const [k, v] of Object.entries(a)) {
      if (FILE_KEYS.includes(k) || FILE_LIST_KEYS.includes(k)) continue;
      if (typeof v === "string") parts.push(`${k}: ${oneLine(v, 120)}`);
      else if (typeof v === "number" || typeof v === "boolean") parts.push(`${k}: ${v}`);
    }
    return oneLine(parts.join(" · ") || JSON.stringify(a), max);
  }
  return oneLine(JSON.stringify(a), max);
}

/** Full text rendering of arguments for the part body (searchable). */
export function argsToText(args: unknown): string {
  const a = parseArgs(args);
  if (a === undefined || a === null) return "";
  if (typeof a === "string") return a;
  if (isRec(a)) {
    // Keep strings verbatim (commands, patches, new file contents) so they are searchable; JSON-encode the rest.
    return Object.entries(a)
      .map(([k, v]) => (typeof v === "string" ? `${k}: ${v}` : `${k}: ${JSON.stringify(v)}`))
      .join("\n");
  }
  return JSON.stringify(a, null, 1);
}

export function oneLine(s: string, max: number): string {
  const one = s.replace(/\s+/g, " ").trim();
  return one.length > max ? one.slice(0, max - 1) + "…" : one;
}

/** Best-effort exit code / error detection on tool output. */
export function detectExit(text: string): { exitCode?: number; isError?: boolean } {
  const m = text.match(/(?:^|\n)\s*(?:exit code|Exit code|exit_code|Process exited with code|Command exited with code)[:=]?\s*(-?\d+)/);
  if (m) {
    const code = Number(m[1]);
    return { exitCode: code, isError: code !== 0 };
  }
  if (/^\s*(Error|error|ERROR|Traceback \(most recent call last\)|fatal:|command not found|No such file or directory|Permission denied)/m.test(text.slice(0, 400))) return { isError: true };
  return {};
}
