/** Tags that wrap the human's actual text; the content is kept as prompt. */
const PROMPT_WRAPPERS = ["user_query", "user_message", "user_prompt", "query", "request", "human"];

const PLAIN_INJECTED_PREFIXES: [RegExp, ContextForm][] = [
  [/^# AGENTS\.md/i, "instructions"],
  [/^# CLAUDE\.md/i, "instructions"],
  [/^<environment_context>/i, "snapshot"],
  [/^<permissions instructions>/i, "instructions"],
  [/^<user_instructions>/i, "instructions"],
  [/^Caveat: The messages below were generated by the user while running local commands/i, "notice"],
  [/^This session is being continued from a previous conversation/i, "recall"],
  [/^The following is the Codex agent history/i, "recall"],
  [/^Briefly inform the user about the task result/i, "notice"],
];

export interface SplitInjected {
  /** Human text with wrappers removed. Empty when the message was pure context. */
  prompt: string;
  context: { form: ContextForm; tag: string; text: string }[];
}

/** `<tag attrs>body</tag>`; group 1 = tag name, group 2 = body. */
const TAG_RE = /<([a-zA-Z_][\w-]*)(?: [^<>]*)?>([\s\S]*?)<\/\1>/g;

/**
 * Split raw user-role text into prompt + context blocks. Handles nested
 * wrappers like `<user_query>...</user_query>` by unwrapping them and keeps
 * unknown tags as prompt text (they may be part of what the user typed).
 */
export function splitInjected(raw: string): SplitInjected {
  const context: SplitInjected["context"] = [];
  let rest = raw;
  // Iteratively strip known tags (handles several at top level; nesting of known tags inside known tags collapses into the outer block).
  let guard = 0;
  while (guard++ < 200) {
    TAG_RE.lastIndex = 0;
    let replaced = false;
    rest = rest.replace(TAG_RE, (whole, tagName: string, body: string) => {
      const tag = tagName.toLowerCase();
      const form = TAG_FORMS[tag];
      if (form) {
        context.push({ form, tag, text: body.trim() });
        replaced = true;
        return "\n";
      }
      if (PROMPT_WRAPPERS.includes(tag)) {
        replaced = true;
        return "\n" + body + "\n";
      }
      return whole;
    });
    if (!replaced) break;
  }
  // Self-closing / attribute-only attachment tags: <image path="…"/>, <file path="…">
  rest = rest.replace(/<(image|img|file|attachment|uploaded_file)\b([^<>]*)\/?>(?:\s*<\/\1>)?/gi, (_w, tag: string, attrs: string) => {
    context.push({ form: "attachment", tag: tag.toLowerCase(), text: attrs.trim() || tag });
    return "\n";
  });
  let prompt = rest.replace(/[ \t]+\n/g, "\n").replace(/\n{3,}/g, "\n\n").trim();
  // A leading bare tag whose closing tag never arrived (truncated titles, streamed prompts) is not human text.
  prompt = prompt.replace(/^(<[a-zA-Z_][\w-]*>\s*)+/, "").trim();
  for (const [re, form] of PLAIN_INJECTED_PREFIXES) {
    if (re.test(prompt)) {
      context.push({ form, tag: "prefix", text: prompt });
      prompt = "";
      break;
    }
  }
  return { prompt, context };
}

/** True when the text is entirely harness-injected. */
export function isInjectedOnly(raw: string): boolean {
  return !splitInjected(raw).prompt;
}

