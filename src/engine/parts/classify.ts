/**
 * Cross-agent classification helpers for the part model.
 *
 * - `splitInjected` separates a raw "user" text into the human prompt and the
 *   context blocks harnesses/IDEs wrap around it (`<system-reminder>`,
 *   `<recommended_plugins>`, `<timestamp>`, `<system_notification>`, ...).
 * - `toolCategory` maps tool names from every agent onto one vocabulary.
 * - `extractFiles` / `extractCommand` pull retrieval keys out of arguments.
 */
import type { ContextForm, ToolCategory } from "./types";

type Rec = Record<string, unknown>;

